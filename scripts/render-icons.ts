// Renders the app icon, the menu bar icon and the README header from the hand-written SVGs in
// assets/icon. Electron's Chromium rasterises each size, so the PNGs match the SVGs as a browser
// draws them, and iconutil packs the app icon sizes into an .icns. Usage: npm run icons
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { app, BrowserWindow } from "electron";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path: string) => readFileSync(join(ROOT, path), "utf8");

const icon = read("assets/icon/icon.svg");
const iconSmall = read("assets/icon/icon-small.svg");
const tray = read("assets/icon/tray.svg");
const wordmark = read("assets/icon/wordmark.svg");

// The .icns slots as [file name, drawing, pixels]. The 16 and 32 px slots get the small-size
// drawing, which is aligned to whole pixels at exactly those sizes.
const ICONSET: [string, string, number][] = [
  ["icon_16x16.png", iconSmall, 16],
  ["icon_16x16@2x.png", iconSmall, 32],
  ["icon_32x32.png", iconSmall, 32],
  ["icon_32x32@2x.png", icon, 64],
  ["icon_128x128.png", icon, 128],
  ["icon_128x128@2x.png", icon, 256],
  ["icon_256x256.png", icon, 256],
  ["icon_256x256@2x.png", icon, 512],
  ["icon_512x512.png", icon, 512],
  ["icon_512x512@2x.png", icon, 1024],
];

/** Copies an SVG into another as a nested <svg>, prefixing its ids so two drawings can't collide.
    An SVG shown through <img>, as on GitHub, can't load other files, so it has to be inlined. */
function nest(svg: string, prefix: string, box: string): string {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replaceAll(/id="([^"]+)"/g, `id="${prefix}-$1"`)
    .replaceAll(/url\(#([^)]+)\)/g, `url(#${prefix}-$1)`);
  return `<svg ${box} viewBox="${viewBox}">${body}</svg>`;
}

/** The README header: a 200 px icon beside the wordmark, whose x-height (y 34 to 80 in the
    wordmark's own units) is centred on the tile. */
function header(ink: string): string {
  const [, top = 0, width = 0, height = 0] = (/viewBox="([^"]+)"/.exec(wordmark)?.[1] ?? "").split(" ").map(Number);
  const scale = 84 / height;
  const x = 180.5 + 34; // the tile's right edge plus a gap
  const y = 100 - (57 - top) * scale;
  const total = Math.ceil(x + width * scale + 4);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${total} 200" width="${total}" height="200">
<!-- Generated by scripts/render-icons.ts from assets/icon. Edit those files and run npm run icons. -->
${nest(icon, "icon", 'x="0" y="0" width="200" height="200"')}
<g color="${ink}">${nest(wordmark, "wordmark", `x="${x}" y="${y.toFixed(1)}" width="${(width * scale).toFixed(1)}" height="84"`)}</g>
</svg>
`;
}

async function main(): Promise<void> {
  const win = new BrowserWindow({ show: false });
  await win.loadURL("about:blank");

  const render = async (svg: string, px: number): Promise<Buffer> => {
    const url = `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;
    const png: string = await win.webContents.executeJavaScript(`(async () => {
      const img = new Image();
      img.src = ${JSON.stringify(url)};
      await img.decode();
      const canvas = document.createElement("canvas");
      canvas.width = canvas.height = ${px};
      canvas.getContext("2d").drawImage(img, 0, 0, ${px}, ${px});
      return canvas.toDataURL("image/png");
    })()`);
    return Buffer.from(png.slice(png.indexOf(",") + 1), "base64");
  };

  const dir = mkdtempSync(join(tmpdir(), "diktatorn-icons-"));
  try {
    const iconset = join(dir, "Diktatorn.iconset");
    mkdirSync(iconset);
    for (const [name, svg, px] of ICONSET) writeFileSync(join(iconset, name), await render(svg, px));
    execFileSync("iconutil", ["--convert", "icns", "--output", join(ROOT, "assets/Diktatorn.icns"), iconset]);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }

  // Development builds run inside Electron's own bundle, so main sets this as the Dock icon.
  writeFileSync(join(ROOT, "assets/icon.png"), await render(icon, 512));
  writeFileSync(join(ROOT, "assets/trayTemplate.png"), await render(tray, 18));
  writeFileSync(join(ROOT, "assets/trayTemplate@2x.png"), await render(tray, 36));
  mkdirSync(join(ROOT, "docs/images"), { recursive: true });
  writeFileSync(join(ROOT, "docs/images/header-light.svg"), header("#0B0F19"));
  writeFileSync(join(ROOT, "docs/images/header-dark.svg"), header("#F2F5FA"));
}

app.dock?.hide();
app.whenReady().then(main).then(
  () => app.quit(),
  (error: unknown) => {
    console.error(error);
    app.exit(1);
  },
);
